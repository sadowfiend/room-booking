import { describe, expect, it } from "vitest";
import { addDays } from "./date";

describe("addDays", () => {
  it.each([
    ["2026-10-07", 0, "2026-10-07"],
    ["2026-10-07", 1, "2026-10-08"],
    ["2026-10-07", -1, "2026-10-06"],
    ["2026-01-31", 1, "2026-02-01"],
    ["2026-10-31", 1, "2026-11-01"],
    ["2026-03-01", -1, "2026-02-28"],
    ["2028-02-28", 1, "2028-02-29"],
    ["2028-02-29", 1, "2028-03-01"],
    ["2028-03-01", -1, "2028-02-29"],
    ["2027-02-28", 1, "2027-03-01"],
    ["2026-12-31", 1, "2027-01-01"],
    ["2027-01-01", -1, "2026-12-31"],
    ["2026-10-07", 30, "2026-11-06"],
    ["2026-10-07", -7, "2026-09-30"],
    ["2026-12-31", 365, "2027-12-31"],
  ])("%s %i -> %s", (date, delta, expected) => {
    expect(addDays(date, delta)).toBe(expected);
  });
});
